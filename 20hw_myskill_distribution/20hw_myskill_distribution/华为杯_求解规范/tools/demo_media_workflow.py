def initialize(root, output, runtime='codex'):
    import rasterio
    from rasterio.transform import Affine
    root, out = Path(root).resolve(), Path(output).resolve()
    out.relative_to(root / '求解/验收输出/academic_figure_integration')
    if 'demo' not in out.name.lower() or out.exists():
        raise ValueError('Choose a new isolated demo directory')
    (out / 'inputs').mkdir(parents=True)
    (out / 'figures').mkdir()
    relative = lambda p: p.relative_to(root).as_posix()
    font = ImageFont.truetype('C:/Windows/Fonts/arial.ttf', 24)
    source = Image.new('RGB', (900, 560), '#f4f6f7')
    draw = ImageDraw.Draw(source)
    draw.text((30, 18), 'DEMO ORIGINAL: native 900 x 560 pixel calibration target', font=font, fill='#171d20')
    for i in range(20):
        for j in range(8):
            c = '#334c59' if (i + j) % 2 else '#ffffff'
            draw.rectangle((30 + 21*i, 100 + 21*j, 50 + 21*i, 120 + 21*j), fill=c)
    for i, color in enumerate(('#176d85', '#c44950', '#53905f', '#a77c22')):
        draw.rectangle((510, 100 + 92*i, 810, 165 + 92*i), fill=color)
    draw.text((30, 340), 'Original geometry and colors are retained.', font=font, fill='#171d20')
    draw.text((30, 382), 'Synthetic target; not experimental evidence.', font=font, fill='#171d20')
    source.save(out / 'inputs/target.png')
    yy, xx = np.mgrid[0:100, 0:140]
    height = (30 + .35*xx + .15*yy + 22*np.exp(-((xx-72)**2/350 + (yy-53)**2/200))).astype('float32')
    with rasterio.open(out / 'inputs/elevation.tif', 'w', driver='GTiff', width=140, height=100,
                       count=1, dtype='float32', crs='EPSG:32648', nodata=-9999,
                       transform=Affine(20, 0, 500000, 0, -20, 2800000)) as ds:
        ds.write(height, 1)
        ds.set_band_unit(1, 'm')
    Image.fromarray(np.rint((height-height.min())/(height.max()-height.min())*255).astype('uint8')).save(out/'inputs/elevation_preview.png')
    write_json(out / 'inputs/synthetic_origin.json', {
        'purpose': 'DEMO ONLY, not observations, not contest evidence',
        'raster': 'Documented artificial height field on a UTM 48N grid; no administrative boundaries',
        'height_formula': '30+0.35*x+0.15*y+22*exp(-((x-72)^2/350+(y-53)^2/200))',
        'grid': '140x100, 20 m pixels, top left E500000 N2800000, EPSG:32648',
        'target': '900x560 native-pixel calibration target generated by this demo initializer'})
    write_json(out/'inventory.json', scan(root, [relative(out/'inputs')]))
    layout = out / 'layout.tex'
    layout.write_text('\\documentclass{article}\n\\usepackage[a4paper,margin=25mm]{geometry}\n'
                      '\\usepackage{graphicx}\n\\usepackage{hyperref}\n\\begin{document}\n'
                      '\\section*{Isolated visual routing DEMO}\n'
                      'Synthetic fixtures only. This document is not a contest paper.\n'
                      '\\begin{figure}[ht]\\centering\\includegraphics[width=150mm]{figures/native.png}\n'
                      '\\caption{Native pixel annotation, DEMO only.}\\label{fig:demo-native}\\end{figure}\n'
                      '\\clearpage\n\\begin{figure}[ht]\\centering\\includegraphics[width=150mm]{figures/terrain.pdf}\n'
                      '\\caption{Artificial spatial field, DEMO only; no administrative boundaries.}'
                      '\\label{fig:demo-terrain}\\end{figure}\n\\end{document}\n', encoding='utf8')
    question = make_problem('q1', 'standard')
    question['claims'] = [{'claim_id': 'q1-C01', 'text': 'DEMO preserves native pixels and explicit spatial metadata'}]
    # Keep the adapted executable in the current run; no hidden skill/tool
    # imports are needed by its scientific rendering subprocess.
    import inspect
    renderer = out / 'render.py'
    renderer.write_text('from pathlib import Path\nfrom PIL import Image, ImageDraw\nimport json, argparse\n'
        'def write_json(path, value):\n    Path(path).write_text(json.dumps(value, ensure_ascii=False), encoding="utf8")\n\n'
        + inspect.getsource(render) + '\n'
        + 'if __name__ == "__main__":\n'
        + '    p=argparse.ArgumentParser(); p.add_argument("--output",required=True); p.add_argument("--render",required=True)\n'
        + '    a=p.parse_args(); print(json.dumps(render(Path.cwd(),a.output,a.render)))\n', encoding='utf8')
    write_json(out / 'renderer-source.json', {'source': '华为杯_求解规范/tools/demo_media_workflow.py',
        'sha256': sha(Path(__file__)), 'adaptation': 'Copy render function with standalone standard JSON writer; DEMO only'})
    script = relative(renderer)
    figures = []
    for name, content, route, family, suffix in (
            ('native', 'image_annotation', 'native_media', 'native_image', 'png'),
            ('terrain', 'terrain', 'domain_render', 'domain_spatial', 'pdf')):
        source_path = out / 'inputs' / ('target.png' if name == 'native' else 'elevation.tif')
        f = {'figure_id': 'demo-' + name, 'scope': 'q1',
             'scientific_question': 'DEMO: inspect ' + name + ' using explicit source information',
             'claim_ids': ['q1-C01'], 'evidence_ids': ['q1-E01'], 'archetype': 'image_plate_quant',
             'layout': 'single panel', 'hero_panel': 'a', 'script': script, 'status': 'planned',
             'count_role': 'illustration',
             'outputs': {'primary': relative(out/'figures'/f'{name}.{suffix}'),
                         'preview': relative(out/'figures'/f'{name}.png')},
             'statistics_report': relative(out/'figures'/f'{name}.stats.json'),
             'qa_report': relative(out/'figures'/f'{name}.qa.json'),
             'paper': {'chapter': 'q1', 'label': 'fig:demo-'+name, 'caption': 'Isolated '+name+' DEMO',
                       'reference_context': 'Synthetic route fixture; no scientific completion claim.'},
             'panels': [{'panel_id': 'a', 'question': 'Inspect source fidelity and spatial/visual interpretation',
                         'figure_type': content, 'figure_family': family, 'result_file': relative(source_path),
                         'fields': ['RGB'] if name == 'native' else ['elevation'], 'units': ['pixel'] if name == 'native' else ['m'],
                         'visual_encoding': 'native color' if name == 'native' else 'continuous height field',
                         'rendering_route': route, 'content_kind': content,
                         'route_reason': 'Direct image or spatial field rendering; no statistical model comparison'}]}
        figures.append(f)
    question['figures'] = figures
    plan = {'schema_version': '1.1', 'project_title': 'ISOLATED MEDIA DEMO', 'plan_status': 'ready',
            'visual_encoding_path': relative(out/'inputs/synthetic_origin.json'),
            'global_figures': [], 'flowcharts': [], 'problems': [question]}
    pp = out / 'demo.json'
    write_json(pp, plan)
    media = prepare(pp, runtime, 'demo')
    for f, rec in zip(figures, media['figures']):
        name = f['figure_id'].removeprefix('demo-')
        rec.update(target_width_mm=150, output_kind='raster' if name == 'native' else 'mixed',
                   scientific_contribution='DEMO illustration only; does not count toward scientific figure quotas',
                   count_role='illustration', run_record_path=relative(out/'figures'/f'{name}.run.json'),
                   qa_path=f['qa_report'])
        rec['paper_geometry'] = {'source_tex': relative(layout), 'source_sha256': sha(layout),
                                 'basis': 'Explicit 150 mm includegraphics in isolated layout.tex'}
        p = rec['panels'][0]
        p['sources'] = [{'path': f['panels'][0]['result_file'], 'sha256': sha(root/f['panels'][0]['result_file']),
                          'role': 'derived', 'origin': 'Synthetic isolated DEMO generated by demo_media_workflow.py',
                          'permission': 'Locally generated synthetic data for implementation verification only',
                          'inventory_path': relative(out/'inventory.json'), 'metadata_reviewed': False,
                          'metadata_observation': ''}]
        p['dependencies'] = [relative(out/'inputs/synthetic_origin.json')]
        p['interpretation'] = 'Synthetic fixture only; no empirical or geographic measurement claim.'
        p['geographic'] = name == 'terrain'
        if name == 'native':
            p['parameters'] = {'pages_frames': [0], 'annotations': 'Red outline around native checkerboard; no crop or resampling',
                               'display_transform': 'identity outside annotation pixels'}
            p['encoding'] = {'kind': 'true_color', 'description': 'Source RGB pixels with explicit annotation only'}
        else:
            p['sources'][0]['preview_path'] = relative(out/'inputs/elevation_preview.png')
            p['dependencies'].append(relative(out/'inputs/elevation_preview.png'))
            p['parameters'] = {'bands': [1], 'nodata': -9999, 'units': 'm', 'source_crs': 'EPSG:32648',
                               'target_crs': 'EPSG:32648', 'resampling': 'none; nearest cell display',
                               'derivation': 'Read documented synthetic elevation band without numerical modification'}
            p['encoding'] = {'kind': 'continuous', 'description': 'Cividis continuous elevation encoding',
                             'variable': 'Synthetic height', 'unit': 'm', 'colorbar': True}
    write_json(media_sidecar(pp), media)
    return {'status': 'DEMO_DRAFT_REQUIRES_REVIEW', 'plan': relative(pp)}


def render(root, output, name):
    out = Path(output).resolve()
    if name == 'native':
        with Image.open(out/'inputs/target.png') as source:
            image = source.convert('RGB')
        draw = ImageDraw.Draw(image)
        draw.rectangle((20, 90, 460, 279), outline='#c44950', width=3)
        image.save(out/'figures/native.png')
        stats = {'purpose': 'DEMO ONLY', 'pixels': list(image.size), 'operation': 'annotation; no resampling'}
    else:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
        import rasterio
        with rasterio.open(out/'inputs/elevation.tif') as ds:
            heights = ds.read(1, masked=True)
            bounds = ds.bounds
        fig, ax = plt.subplots(figsize=(150/25.4, 113/25.4), layout='constrained')
        image = ax.imshow(heights, extent=[bounds.left, bounds.right, bounds.bottom, bounds.top],
                          cmap='cividis', origin='upper', interpolation='nearest')
        fig.colorbar(image, ax=ax, label='Synthetic height (m)', shrink=.78)
        ax.set(title='DEMO: artificial spatial field (UTM 48N)', xlabel='Easting (m)', ylabel='Northing (m)')
        ax.ticklabel_format(style='plain', useOffset=False)
        ax.tick_params(labelsize=8)
        ax.grid(color='white', linewidth=.4, alpha=.4)
        ax.annotate('N', xy=(502520, 2799780), xytext=(502520, 2799390), ha='center',
                    arrowprops={'arrowstyle': '-|>', 'color': 'white'}, color='white')
        ax.plot([500150, 500650], [2798150, 2798150], color='white', lw=3)
        ax.text(500400, 2798230, '500 m', color='white', ha='center', fontsize=9)
        fig.savefig(out/'figures/terrain.pdf')
        fig.savefig(out/'figures/terrain.png', dpi=200)
        plt.close(fig)
        stats = {'purpose': 'DEMO ONLY', 'shape': list(heights.shape), 'min_m': float(heights.min()),
                 'max_m': float(heights.max()), 'crs': 'EPSG:32648', 'cell_size_m': 20}
    write_json(out/'figures'/f'{name}.stats.json', stats)
    return stats


