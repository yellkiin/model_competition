def evaluation_text(short=False, extra=False):
    parts = [r'\section{模型评价与展望}']
    for title, values in (('模型优点', ADVANTAGES), ('模型缺点', LIMITATIONS)):
        parts.extend(['\\subsection{' + title + '}', r'\begin{enumerate}'])
        for label, explanation in values:
            if short:
                explanation = explanation.split('。')[0] + '。'
            parts.append('\\item \\textbf{' + label + '。}' + explanation)
        parts.append(r'\end{enumerate}')
    parts.append(r'\subsection{模型的推广与改进}')
    parts.append('\n\n'.join(p.split('。')[0] + '。' if short else p for p in OUTLOOK))
    if extra:
        parts.append('\n另一个需要验证的方向是审阅记录的失效处理。正文修改后，旧观察不能继续代表当前页面；重建记录应保留待审状态，直至观察者实际打开新的图像并复核。维护实验应分别改变正文、页面和测量数据，观察检查能否发现不一致，以确定证据绑定的覆盖范围。该计划尚不能替代实际执行结果。')
    return '\n\n'.join(parts) + '\n'
